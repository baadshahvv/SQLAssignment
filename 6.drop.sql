-- Section 6 : DROP Command
-- =====================================================

-- Q1. What is the function of the DROP command in SQL?
-- The DROP command is used to permanently delete
-- database objects such as tables or databases.

-- Q2. What are the implications of dropping a table from a database?
-- Dropping a table removes all data, structure,
-- indexes, and constraints permanently and
-- cannot be recovered without backup.

